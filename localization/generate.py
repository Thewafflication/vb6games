#!/usr/bin/env python3
"""Generate each game's modLocale.bas from localization/<game>.csv.

The CSV files (UTF-8, columns: key,en,pl,zh,es) are the source of truth.
VB6 source files are ANSI, so the generated module is pure ASCII: text outside
ASCII is written as hexadecimal UTF-16 code units that U() turns into ChrW
characters at run time.

Usage: python generate.py [game ...]      (default: every game)
"""
import csv
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)

# game -> directory (relative to the repository root) that receives modLocale.bas
GAMES = {
    "pipes": "pipes",
    "restaum": "restaum/source",
    "connect4": "connect4/Modules",
    "clix": "clix/src",
    "executioner": "executioner",
    "sumboku": "sumboku/Modules",
    "captureking": "captureking",
}

LANGS = ["en", "pl", "zh", "es"]
CHUNK_KEYS = 40     # keys per generated Sub (keeps procedures small)
CHUNK_CHARS = 120   # characters per literal piece of a long string

HEADER = """Attribute VB_Name = "modLocale"
Option Explicit
'
' Localization (English, Polish, Chinese and Spanish).
'
' GENERATED from localization/{game}.csv by localization/generate.py;
' edit the CSV and regenerate, do not edit this file by hand.
'
' The language is chosen from the user's Windows display language. English is
' the default for every other language. The environment variable
' VB6GAMES_LANG (en, pl, zh or es) overrides the detection.
'
Private Declare Function GetUserDefaultUILanguage Lib "kernel32" () As Integer

Private mCode As String
Private mText As Collection

' The language in use: "en", "pl", "zh" or "es".
Public Function LocLanguage() As String
    If mText Is Nothing Then Initialize
    LocLanguage = mCode
End Function

' The text of a key in the language in use.
Public Function Loc(ByVal Key As String) As String
    If mText Is Nothing Then Initialize
    On Error Resume Next
    Err.Clear
    Loc = mText(Key)
    If Err.Number <> 0 Then Loc = Key
End Function

' The text of a key with {{0}}, {{1}}, ... replaced by the arguments.
Public Function LocF(ByVal Key As String, ParamArray Args() As Variant) As String
    Dim s As String
    Dim i As Long
    s = Loc(Key)
    For i = LBound(Args) To UBound(Args)
        s = Replace(s, "{{" & CStr(i - LBound(Args)) & "}}", CStr(Args(i)))
    Next i
    LocF = s
End Function

Private Sub Initialize()
    Set mText = New Collection
    mCode = DetectLanguage()
    AddEnglish
    Select Case mCode
    Case "pl": AddPolish
    Case "zh": AddChinese
    Case "es": AddSpanish
    End Select
End Sub

Private Function DetectLanguage() As String
    Dim s As String
    Dim id As Long
    s = LCase$(Left$(Trim$(Environ$("VB6GAMES_LANG")), 2))
    Select Case s
    Case "en", "pl", "zh", "es"
        DetectLanguage = s
        Exit Function
    End Select
    DetectLanguage = "en"
    On Error GoTo Done
    id = GetUserDefaultUILanguage() And &H3FF
    Select Case id
    Case &H15: DetectLanguage = "pl"
    Case &H4: DetectLanguage = "zh"
    Case &HA: DetectLanguage = "es"
    End Select
Done:
End Function

Private Sub P(ByVal Key As String, ByVal Text As String)
    On Error Resume Next
    mText.Remove Key
    Err.Clear
    mText.Add Text, Key
End Sub

' Turns a string of four-digit hexadecimal UTF-16 code units into text.
Private Function U(ByVal Hex4 As String) As String
    Dim i As Long
    Dim s As String
    For i = 1 To Len(Hex4) Step 4
        s = s & ChrW(CLng("&H" & Mid$(Hex4, i, 4) & "&"))
    Next i
    U = s
End Function
"""


def literal(text):
    """VB expressions for text, split so no source line gets too long.

    {nl} and {tab} in the CSV become vbCrLf and vbTab."""
    pieces = []
    for part in re.split(r"(\{nl\}|\{tab\})", text):
        if part == "{nl}":
            pieces.append("vbCrLf")
        elif part == "{tab}":
            pieces.append("vbTab")
        else:
            pieces += [part[i:i + CHUNK_CHARS]
                       for i in range(0, len(part), CHUNK_CHARS)]
    pieces = pieces or [""]
    out = []
    for piece in pieces:
        if piece in ("vbCrLf", "vbTab"):
            out.append(piece)
        elif all(32 <= ord(c) < 127 for c in piece):
            out.append('"' + piece.replace('"', '""') + '"')
        else:
            hex_units = "".join(
                "%04X" % unit
                for unit in memoryview(piece.encode("utf-16-le")).cast("H")
            )
            out.append('U("' + hex_units + '")')
    return out


def emit_put(key, text):
    pieces = literal(text)
    if len(pieces) == 1:
        return ['    P "%s", %s' % (key, pieces[0])]
    lines = ["    s = " + pieces[0]]
    lines += ["    s = s & " + piece for piece in pieces[1:]]
    lines.append('    P "%s", s' % key)
    return lines


def emit_sub(name, rows, lang):
    index = LANGS.index(lang)
    chunks = [rows[i:i + CHUNK_KEYS] for i in range(0, len(rows), CHUNK_KEYS)]
    out = []
    for number, chunk in enumerate(chunks, 1):
        out.append("")
        out.append("Private Sub %s%d()" % (name, number))
        out.append("    Dim s As String")
        for row in chunk:
            out += emit_put(row[0], row[1 + index])
        out.append("End Sub")
    out.append("")
    out.append("Private Sub %s()" % name)
    for number in range(1, len(chunks) + 1):
        out.append("    %s%d" % (name, number))
    out.append("End Sub")
    return out


def load(game):
    path = os.path.join(HERE, game + ".csv")
    with open(path, encoding="utf-8-sig", newline="") as handle:
        rows = [r for r in csv.reader(handle) if r and r[0] and r[0][0] != "#"]
    if rows[0][0].lower() == "key":
        rows = rows[1:]
    seen = set()
    for row in rows:
        if len(row) != 5:
            sys.exit("%s: %s: expected 5 columns, got %d" % (game, row[0], len(row)))
        if not re.fullmatch(r"[A-Za-z0-9_.]+", row[0]):
            sys.exit("%s: bad key %r" % (game, row[0]))
        if row[0] in seen:
            sys.exit("%s: duplicate key %s" % (game, row[0]))
        seen.add(row[0])
        placeholders = [sorted(set(re.findall(r"\{\d+\}", cell))) for cell in row[1:]]
        for lang, found in zip(LANGS, placeholders):
            if found != placeholders[0]:
                sys.exit("%s: %s: placeholders differ in %s" % (game, row[0], lang))
        for lang, cell in zip(LANGS[1:], row[2:]):
            if cell == "":
                sys.exit("%s: %s: %s is empty" % (game, row[0], lang))
    return rows


def generate(game):
    rows = load(game)
    lines = HEADER.format(game=game).rstrip("\n").split("\n")
    for name, lang in (("AddEnglish", "en"), ("AddPolish", "pl"),
                       ("AddChinese", "zh"), ("AddSpanish", "es")):
        lines += emit_sub(name, rows, lang)
    text = "\r\n".join(lines) + "\r\n"
    out_dir = os.path.join(ROOT, GAMES[game])
    with open(os.path.join(out_dir, "modLocale.bas"), "w", newline="") as handle:
        handle.write(text)
    print("%s: %d keys -> %s/modLocale.bas" % (game, len(rows), GAMES[game]))


if __name__ == "__main__":
    for game in sys.argv[1:] or GAMES:
        if os.path.exists(os.path.join(HERE, game + ".csv")):
            generate(game)
